import { GLYPH_BRIGHTNESS as CASCADIA_MONO } from './brightness/cascadia-mono';
import { GLYPH_BRIGHTNESS as FIRA_MONO } from './brightness/fira-mono';
import { GLYPH_BRIGHTNESS as IBM_PLEX_MONO } from './brightness/ibm-plex-mono';
import { GLYPH_BRIGHTNESS as JETBRAINS_MONO } from './brightness/jetbrains-mono';

/** Characters with their brightness (ink coverage, 1 = brightest), darkest first. */
export type GlyphTable = readonly (readonly [char: string, brightness: number])[];

/**
 * A font face a document can use. Fonts are self-hosted via @fontsource
 * (imported in styles.css) so documents look the same on every machine.
 */
export interface FontConfig {
  id: string;
  /** Display name. */
  name: string;
  /** CSS font-family value (with generic fallback). */
  family: string;
  /** Cell height as a multiple of the font size. */
  lineHeight: number;
  /** Available weights, ascending. */
  weights: readonly number[];
  /** Brightness table per weight (bolder glyphs cover more). Generated by `npm run gen:fonts`. */
  glyphsByWeight: Readonly<Record<number, GlyphTable>>;
}

export const DEFAULT_FONT_WEIGHT = 400;

export const WEIGHT_NAMES: Readonly<Record<number, string>> = {
  100: 'Thin',
  200: 'Extra Light',
  300: 'Light',
  400: 'Regular',
  500: 'Medium',
  600: 'Semi Bold',
  700: 'Bold',
  800: 'Extra Bold',
  900: 'Black',
};

function font(id: string, name: string, glyphsByWeight: FontConfig['glyphsByWeight']): FontConfig {
  return {
    id,
    name,
    family: `"${name}", monospace`,
    lineHeight: 1.2,
    weights: Object.keys(glyphsByWeight).map(Number).sort((a, b) => a - b),
    glyphsByWeight,
  };
}

export const FONTS: readonly FontConfig[] = [
  font('cascadia-mono', 'Cascadia Mono', CASCADIA_MONO),
  font('jetbrains-mono', 'JetBrains Mono', JETBRAINS_MONO),
  font('ibm-plex-mono', 'IBM Plex Mono', IBM_PLEX_MONO),
  font('fira-mono', 'Fira Mono', FIRA_MONO),
];

export const DEFAULT_FONT_ID = 'cascadia-mono';

export function getFont(id: string): FontConfig {
  const f = FONTS.find((x) => x.id === id);
  if (!f) throw new Error(`Unknown font: ${id}`);
  return f;
}

/** The font's weight closest to the one asked for (ties go to the lighter). */
export function nearestWeight(font: FontConfig, weight: number): number {
  return font.weights.reduce((best, w) => (Math.abs(w - weight) < Math.abs(best - weight) ? w : best));
}

/** Brightness table for a font at a weight (nearest available). */
export function glyphsFor(font: FontConfig, weight: number): GlyphTable {
  return font.glyphsByWeight[nearestWeight(font, weight)];
}

/** CSS / canvas font shorthand. */
export function fontCss(font: FontConfig, weight: number, sizePx: number): string {
  return `${weight} ${sizePx}px ${font.family}`;
}

/** Resolves once the font's glyphs at this weight are available for canvas drawing. */
export async function loadFont(font: FontConfig, weight = DEFAULT_FONT_WEIGHT): Promise<void> {
  if (typeof document === 'undefined' || !document.fonts) return;
  await document.fonts.load(fontCss(font, weight, 16));
}
